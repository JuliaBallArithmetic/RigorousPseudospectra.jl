# The certified resolvent floor of the splitting (Theorem thm:assembly with eq:farshort) on the
# gallery, one figure per matrix, written to bench/figures/split_<name>.png, and a table in
# bench/REPORT.md. For each matrix: a two-sided frame of Definition def:Q with ks = n/4 singular
# directions per side, one certified split, and on a grid over the gallery's box the certified
# lower bound on σ_min(A − zI) (grey where there is none, which includes the disc |z| ≤ ḡ, drawn
# dashed), with the dense σ_min = ε contour and the eigenvalues overlaid.
#
#   julia --project=bench bench/figures.jl

using RigorousPseudospectra
using CairoMakie
using LinearAlgebra
using Printf

include(joinpath(@__DIR__, "matrices.jl"))

const FIGDIR = joinpath(@__DIR__, "figures")
mkpath(FIGDIR)

# a transfer-operator-like smoothing kernel: decaying singular values
function smoothing(n; w = 0.05)
    xs = range(0, 1; length = n)
    A = [exp(-((xs[i] - xs[j]) / w)^2) for i in 1:n, j in 1:n]
    return A ./ sum(A; dims = 2)
end

function entries()
    es = collect(gallery())
    push!(es, (name = "smoothing120", A = smoothing(120), box = (-1.2 - 1.2im, 1.2 + 1.2im),
        ε = 0.05, h = 0.0))
    return es
end

function make_figure(e; ng = 110)
    A = Matrix(e.A)
    n = size(A, 1)
    T = eltype(A) <: Complex ? ComplexF64 : Float64
    ks = max(2, n ÷ 4)
    t_split = @elapsed begin
        Q, _ = two_sided_frame(x -> A * x, x -> A' * x, n, 0.0; ks, keig = false, T)
        sc = certify_split(A, Q)
    end
    lo, hi = e.box
    xs = range(real(lo), real(hi); length = ng)
    ys = range(imag(lo), imag(hi); length = ng)
    t_grid = @elapsed F = [resolvent_floor(sc, x + im * y).floor for x in xs, y in ys]
    Tm = [svdvals(A - (x + im * y) * I)[end] for x in xs, y in ys]
    L = [f > 0 ? log10(f) : NaN for f in F]
    fig = Figure(size = (720, 660))
    ax = Axis(fig[1, 1]; xlabel = "Re z", ylabel = "Im z", aspect = DataAspect(),
        title = "$(e.name): n = $n, dim Q = $(sc.k), ḡ = $(round(sc.gbar; sigdigits = 3))")
    fin = filter(isfinite, L)
    cr = isempty(fin) ? (0.0, 1.0) : (minimum(fin), maximum(fin))
    hm = heatmap!(ax, xs, ys, L; colormap = :viridis, colorrange = cr,
        nan_color = RGBAf(0.6, 0.6, 0.6, 1))
    contour!(ax, xs, ys, Tm; levels = [e.ε], color = :black, linewidth = 2)
    θ = range(0, 2π; length = 200)
    lines!(ax, sc.gbar .* cos.(θ), sc.gbar .* sin.(θ); color = :white, linestyle = :dash)
    ev = eigvals(A)
    scatter!(ax, real.(ev), imag.(ev); marker = :xcross, color = :red, markersize = 8)
    Colorbar(fig[1, 2], hm; label = "log₁₀ certified lower bound on σ_min(A − zI)")
    png = "split_$(e.name).png"
    save(joinpath(FIGDIR, png), fig)
    cert = F .> 0
    ratio = F[cert] ./ Tm[cert]
    return (; name = e.name, n, k = sc.k, gbar = sc.gbar, γ1 = sc.γ1, γ2 = sc.γ2,
        frac = count(cert) / length(F), rmin = isempty(ratio) ? NaN : minimum(ratio),
        rmed = isempty(ratio) ? NaN : sort(ratio)[cld(length(ratio), 2)],
        viol = count(F .> Tm .* (1 + 1e-10) .+ 1e-14), t_split, t_grid, png)
end

results = [make_figure(e) for e in entries()]

open(joinpath(@__DIR__, "REPORT.md"), "w") do io
    println(io, "# The certified split on the gallery\n")
    println(io, "Generated by `bench/figures.jl`. For each matrix, a two-sided frame (ks = n/4 per ",
        "side), one certified split, and the certified lower bound on σ_min(A − zI) of ",
        "Theorem thm:assembly with eq:farshort on a grid. Grey: no bound; dashed white: |z| = ḡ; ",
        "black: the dense σ_min = ε contour; red: eigenvalues.\n")
    println(io, "`certified` is the fraction of grid points with a bound; `bound/σ_min` the least ",
        "and the median ratio of the bound to the dense σ_min over those points; `viol` the number ",
        "of points where the bound exceeded the dense value.\n")
    println(io, "| matrix | n | dim Q | ḡ | γ1 | γ2 | certified | bound/σ_min min | median | viol | split (s) | grid (s) |")
    println(io, "|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in results
        @printf(io, "| %s | %d | %d | %.3e | %.3e | %.3e | %.3f | %.3f | %.3f | %d | %.2f | %.2f |\n",
            r.name, r.n, r.k, r.gbar, r.γ1, r.γ2, r.frac, r.rmin, r.rmed, r.viol, r.t_split,
            r.t_grid)
    end
    println(io)
    for r in results
        println(io, "## $(r.name)\n\n![$(r.name)](figures/$(r.png))\n")
    end
end

for r in results
    @printf("%-14s n=%4d dimQ=%3d ḡ=%.3e certified=%.3f ratio min/median=%.3f/%.3f viol=%d\n",
        r.name, r.n, r.k, r.gbar, r.frac, r.rmin, r.rmed, r.viol)
end
println("wrote ", joinpath(@__DIR__, "REPORT.md"))
