# Generate the pseudospectrum-enclosure report: one figure per gallery matrix
# (certified enclosure + the true ε-contour overlaid for validation) plus a stats
# table, written to bench/figures/*.png and bench/REPORT.md.
#
# Run from the bench environment (see bench/README.md):
#   julia --project=bench bench/figures.jl

using RigorousPseudospectra
using CairoMakie
using LinearAlgebra
using Printf

include(joinpath(@__DIR__, "matrices.jl"))

const FIGDIR = joinpath(@__DIR__, "figures")
mkpath(FIGDIR)

# true σ_min on a grid over the box, for the ground-truth ε-contour overlay
function true_sigma_grid(A, box; ng = 140)
    lo, hi = box
    xs = range(real(lo), real(hi); length = ng)
    ys = range(imag(lo), imag(hi); length = ng)
    M = ComplexF64.(Matrix(A))
    Z = [svdvals(M - (x + im * y) * I)[end] for x in xs, y in ys]
    return collect(xs), collect(ys), Z
end

function make_figure(entry)
    A = entry.A
    box, ε, h = entry.box, entry.ε, entry.h
    certified_setup(A)                       # warm up
    t_setup = @elapsed (cf = cheap_floor(A))
    local enc
    t_sweep = @elapsed (enc = bisect(cf; box = box, ε = ε, min_halfdiag = h))

    fig = Figure(size = (720, 680))
    ax = Axis(fig[1, 1]; xlabel = "Re z", ylabel = "Im z", aspect = DataAspect(),
        title = "$(entry.name)   (n = $(size(A, 1)),  ε = $ε)")
    plot_enclosure!(ax, enc)
    xs, ys, Zg = true_sigma_grid(A, box)
    contour!(ax, xs, ys, Zg; levels = [ε], color = :black, linewidth = 2)
    png = entry.name * ".png"
    save(joinpath(FIGDIR, png), fig)

    return (; name = entry.name, n = size(A, 1), ε = ε, h = h,
        nex = length(enc.excluded), nin = length(enc.included),
        nbd = length(enc.boundary), routing = routing_histogram(enc),
        t_setup, t_sweep, png)
end

results = [make_figure(e) for e in gallery()]

open(joinpath(@__DIR__, "REPORT.md"), "w") do io
    println(io, "# Pseudospectrum enclosure report\n")
    println(io, "Certified ε-pseudospectrum enclosures from the box-bisection sweep ",
        "(`RigorousPseudospectra.bisect`). Generated by `bench/figures.jl`.\n")
    println(io, "**Legend.** Grey = certified *outside* σ_ε (resolvent provably ",
        "small); blue = certified *inside* σ_ε; red = unresolved boundary cells ",
        "(the ε-contour at target resolution); black × = approximate eigenvalues; ",
        "**solid black curve = the true σ_min = ε contour** (dense-SVD ground ",
        "truth) — the certified blue/grey regions must bracket it.\n")
    println(io, "| matrix | n | ε | excluded | included | boundary | routing | ",
        "setup (s) | sweep (s) |")
    println(io, "|---|---|---|---|---|---|---|---|---|")
    for r in results
        rt = join(["$k:$v" for (k, v) in r.routing], ", ")
        @printf(io, "| %s | %d | %g | %d | %d | %d | %s | %.3f | %.2f |\n",
            r.name, r.n, r.ε, r.nex, r.nin, r.nbd, rt, r.t_setup, r.t_sweep)
    end
    println(io)
    for r in results
        println(io, "## $(r.name)\n")
        println(io, "![$(r.name)](figures/$(r.png))\n")
    end
    println(io, "\n*Method.* The sweep is tiered cheapest-first: the cheap scalar ",
        "floors (free triangular gap, SVD-frame, recentred) with the resolvent ",
        "maximum principle on eigenvalue-free cells, then — only where those are ",
        "inconclusive — escalation to the **block/cluster tier** (`gap_cluster`, a ",
        "tight per-z verified-SVD bound on each coupling-graph cluster, built once ",
        "and cached). The `routing` column shows which tier settled each excluded ",
        "cell: normal matrices resolve entirely on `triangular`; strongly ",
        "non-normal / clustered ones (`grcar`, `jordan`, `two_clusters`) escalate to ",
        "`cluster`. Either way the result is a thin certified contour bracketing the ",
        "true level set.")
end

println("wrote ", joinpath(@__DIR__, "REPORT.md"), " and ", length(results),
    " figures to ", FIGDIR)
for r in results
    println(@sprintf("  %-13s ex=%-5d in=%-5d bd=%-6d  %s",
        r.name, r.nex, r.nin, r.nbd, string(r.routing)))
end
